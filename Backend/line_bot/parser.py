def find_numbers(text):
    """คืนยอดเงินพร้อมตำแหน่ง โดยรับตัวเลขที่มี comma และทศนิยมไม่เกิน 2 หลัก"""
    found = []
    pattern = r"(?<![\dA-Za-z])(?:\d{1,3}(?:,\d{3})+|\d+)(?:\.\d{1,2})?(?![\dA-Za-z])"
    for match in re.finditer(pattern, text):
        raw = match.group()
        value = float(raw.replace(",", ""))
        found.append((value, match.start(), match.end()))
    return found


def has_invalid_number(text):
    """กันรูปแบบตัวเลขผิด เช่น 50. / .5 / 50.5.5 / 1e3 / 1,25"""
    if re.search(r"[0-9]\.(?![0-9])|[0-9],[^0-9]|(?<![0-9])\.[0-9]|[0-9]\.[0-9]{3,}|[0-9]\.[0-9]+\.[0-9]", text):
        return True
    if re.search(r"[0-9][eE][+-]?[0-9]|[0-9],[0-9]{1,2}(?![0-9])", text):
        return True
    return False


def contains_date(text):
    """ตรวจวันที่รูปแบบ 12/11/2026 หรือ 12-11-2026"""
    for separator in DATE_SEPARATORS:
        if separator not in text:
            continue
        for word in text.split():
            parts = word.strip(" ,:()[]").split(separator)
            if len(parts) != 3:
                continue

            valid_parts = True
            for part in parts:
                if not part.isdigit():
                    valid_parts = False
                    break

            if valid_parts and len(parts[2]) in (2, 4):
                return True
    return False


def get_amount_and_ranges(text):
    """รับยอดเงินเดียวที่เป็นเงินบาท และปฏิเสธข้อความกำกวม"""
    if re.search(r"(?<![0-9A-Za-z])-[ \t]*[0-9]", text):
        return None, [], "จำนวนเงินต้องมากกว่า 0 บาท กรุณาพิมพ์รายการใหม่"

    if re.search(r"\b(?:USD|EUR|GBP|JPY|CNY|THB)\b", text, re.IGNORECASE):
        if not re.search(r"\bTHB\b", text, re.IGNORECASE) or re.search(r"\b(?:USD|EUR|GBP|JPY|CNY)\b", text, re.IGNORECASE):
            return None, [], "รองรับเฉพาะสกุลเงินบาท กรุณาพิมพ์รายการใหม่"

    if has_invalid_number(text):
        return None, [], "รูปแบบจำนวนเงินไม่ถูกต้อง กรุณาพิมพ์ใหม่ เช่น ชาเขียว 50.50 บาท"

    numbers = find_numbers(text)
    if not numbers:
        return None, [], "ไม่พบจำนวนเงินที่ถูกต้อง"
    if len(numbers) > 1:
        return None, [], "พบตัวเลขหลายจำนวน กรุณาระบุยอดสุทธิเป็นจำนวนเงินเดียว"

    amount, start, end = numbers[0]
    if amount <= 0:
        return None, [], "จำนวนเงินต้องมากกว่า 0 บาท"
    return amount, [(start, end)], ""


def remove_keyword(text, keyword):
    """ลบคำที่พบแบบไม่สนใจตัวพิมพ์เล็กใหญ่"""
    position = text.lower().find(keyword.lower())
    if position < 0:
        return text
    return text[:position] + text[position + len(keyword):]


def remove_ranges(text, ranges):
    """ลบช่วงข้อความจากท้ายไปต้นเพื่อคงตำแหน่งของช่วงที่เหลือ"""
    for start, end in sorted(ranges, reverse=True):
        text = text[:start] + text[end:]
    return text


def clean_item_name(item_name, transaction_type, matched_account):
    """ลบชื่อบัญชี หน่วยเงิน และคำขึ้นต้น โดยรักษาชื่อสินค้าจริง"""
    if matched_account:
        item_name = remove_keyword(item_name, matched_account)

    # ลบหน่วยเงินที่ติดกับยอดเงินหรือแยกด้วยช่องว่าง
    item_name = re.sub(r"(?:บาท|บ\.|฿|THB|baht)", " ", item_name, flags=re.IGNORECASE)
    item_name = " ".join(item_name.split())

    if transaction_type == "expense":
        for store in STORE_MARKETS:
            if item_name.lower().endswith(store) and len(item_name) > len(store):
                item_name = item_name[:-len(store)].strip()
                break

    for prefix, removal in PREFIX_REMOVALS:
        if item_name.startswith(prefix):
            if removal:
                item_name = item_name[len(removal):]
            break

    return item_name.strip(" -, :\t")


